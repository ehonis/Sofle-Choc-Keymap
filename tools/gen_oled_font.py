"""Generate oled_font.h: 1-bit bitmaps of the counter glyphs, rasterized from a TTF.

The OLED counter draws two glyph sizes, both sitting on one baseline:
  * big   - digits 0-9 and '.', digit height BIG_H px, proportional widths
  * small - digits 0-9 (fixed cell so ticking digits do not jitter) plus k and m,
            digit height SMALL_H px

Glyphs are rendered 8x oversized, box-filtered down and thresholded, which gives
noticeably cleaner 1-bit shapes than rendering at the target size directly.

Usage (needs Pillow; any Python 3):
    python -m pip install pillow
    curl -L -o Oswald.ttf "https://raw.githubusercontent.com/google/fonts/main/ofl/oswald/Oswald%5Bwght%5D.ttf"
    python tools/gen_oled_font.py Oswald.ttf oled_font.h --weight 500

The default font is Oswald (SIL Open Font License 1.1, Copyright 2016 The Oswald
Project Authors, https://github.com/googlefonts/OswaldFont).
"""
import argparse
from PIL import Image, ImageDraw, ImageFont

SS = 8
BIG_H, SMALL_H = 29, 16
THRESH = 0.5

# Glyph codes must match keymap.c: 0-9 big digits, 10 '.', 11 'k', 12 'm', 16-25 small digits.
CODE_DOT, CODE_K, CODE_M, CODE_SMALL0 = 10, 11, 12, 16
TABLE_LEN = 26


def font_maker(path, weight):
    def mk(size):
        f = ImageFont.truetype(path, size)
        if weight is not None:
            f.set_variation_by_axes([weight])
        return f
    return mk


def rasterize(mk, chars, digit_h):
    """Return {ch: rows} where rows is a list of bool lists, bottom row on the baseline."""
    probe = mk(100)
    bb = probe.getbbox("0", anchor="ls")
    size = round(100 * digit_h * SS / (bb[3] - bb[1]))
    f = mk(size)
    top = f.getbbox("0", anchor="ls")[1]  # negative: digit top relative to baseline
    head = digit_h // 2                   # room above the digit top for taller glyphs (k)
    out = {}
    for ch in chars:
        canvas_h = (digit_h + head) * SS
        img = Image.new("L", (size * 2, canvas_h), 0)
        # Baseline lands exactly on the bottom edge of the canvas, so anything below it
        # (the sub-pixel overshoot of round digits) is clipped.
        ImageDraw.Draw(img).text((size // 2, canvas_h), ch, font=f, fill=255, anchor="ls")
        small = img.resize((img.width // SS, img.height // SS), Image.BOX)
        px = small.load()
        rows = [[px[x, y] >= THRESH * 255 for x in range(small.width)] for y in range(small.height)]
        cols = [x for x in range(small.width) if any(r[x] for r in rows)]
        lit = [y for y, r in enumerate(rows) if any(r)]
        out[ch] = [r[cols[0]:cols[-1] + 1] for r in rows[lit[0]:]]
    return out


def pack(rows):
    data = []
    for r in rows:
        for i in range(0, len(r), 8):
            byte = 0
            for b, on in enumerate(r[i:i + 8]):
                if on:
                    byte |= 0x80 >> b
            data.append(byte)
    return data


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("font")
    ap.add_argument("out")
    ap.add_argument("--weight", type=float, default=None, help="variable-font weight axis value")
    args = ap.parse_args()

    mk = font_maker(args.font, args.weight)
    big = rasterize(mk, "0123456789.", BIG_H)
    small = rasterize(mk, "0123456789km", SMALL_H)
    small_cell = max(len(small[d][0]) for d in "0123456789")

    entries = [None] * TABLE_LEN
    for d in range(10):
        entries[d] = (str(d), big[str(d)], len(big[str(d)][0]), 0)
        rows = small[str(d)]
        w = len(rows[0])
        entries[CODE_SMALL0 + d] = (f"small {d}", rows, small_cell, (small_cell - w) // 2)
    entries[CODE_DOT] = (".", big["."], len(big["."][0]), 0)
    entries[CODE_K] = ("k", small["k"], len(small["k"][0]), 0)
    entries[CODE_M] = ("m", small["m"], len(small["m"][0]), 0)

    bits, table = [], []
    for e in entries:
        if e is None:
            table.append("    {0, 0, 0, 0, 0},")
            continue
        name, rows, cell, xoff = e
        table.append(f"    {{{len(rows[0])}, {len(rows)}, {cell}, {xoff}, {len(bits)}}}, /* {name} */")
        bits += pack(rows)

    lines = [
        "/* Generated by tools/gen_oled_font.py - do not edit by hand. */",
        "/*",
        " * Counter glyphs rasterized from Oswald (SIL Open Font License 1.1,",
        " * Copyright 2016 The Oswald Project Authors, https://github.com/googlefonts/OswaldFont).",
        " *",
        " * Each glyph is row-major, MSB = leftmost pixel, ceil(w / 8) bytes per row, and its",
        " * bottom row sits on the baseline. `cell` is the layout width; the ink is drawn",
        " * `xoff` px into it (small digits share one fixed cell so they do not jitter).",
        " */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "#include \"progmem.h\"",
        "",
        "typedef struct {",
        "    uint8_t  w, h, cell, xoff;",
        "    uint16_t offset; /* into oled_glyph_bits */",
        "} oled_glyph_t;",
        "",
        f"#define OLED_FONT_BIG_H {BIG_H}",
        f"#define OLED_FONT_SMALL_H {SMALL_H}",
        "",
        f"static const oled_glyph_t PROGMEM oled_glyphs[{TABLE_LEN}] = {{",
        *table,
        "};",
        "",
        f"static const uint8_t PROGMEM oled_glyph_bits[{len(bits)}] = {{",
    ]
    for i in range(0, len(bits), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in bits[i:i + 16]) + ",")
    lines.append("};")
    with open(args.out, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {args.out}: {len(bits)} bytes of bitmap, small cell {small_cell}px")


if __name__ == "__main__":
    main()
